// Packs the PNGs in assets/ into one small sprite sheet and embeds it in
// src/sprites.ts as a data URI, so the game never needs the network or a
// bundler asset server to draw (a dev build that's offline can't reach Metro).
// The sheet is a 16-colour palette PNG, which is a fraction of the size of
// the RGBA originals.
// Run with: node scripts/generate-sprites.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { deflateSync } from 'node:zlib';
import { PNG } from 'pngjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const load = (name) => PNG.sync.read(readFileSync(join(root, 'assets', `${name}.png`)));

// [name, source file, x, y, width, height] of each sprite in its source.
// The ground strip only has pixels in rows 20-28, and cloud.png holds four
// copies of the same 46x13 cloud.
const SPRITES = [
  ['ground', 'ground', 0, 20, 1360, 9],
  ['dino', 'dino', 0, 0, 40, 44],
  ['dinoLeft', 'dino-left', 0, 0, 40, 44],
  ['dinoRight', 'dino-right', 0, 0, 40, 44],
  ['dinoDead', 'dino-dead', 0, 0, 40, 44],
  ['obstacle', 'obstacle', 0, 0, 25, 23],
  ['cloud', 'cloud', 262, 4, 46, 13],
];

// The ground goes along the top, everything else in a row underneath, with
// transparent gaps so scaling a sprite on screen never blends in the edge of
// its neighbour.
const GAP = 2;
const placed = [];
let x = 0;
for (const [name, file, sx, sy, w, h] of SPRITES) {
  const [dx, dy] = name === 'ground' ? [0, 0] : [x, 9 + GAP];
  if (name !== 'ground') x += w + GAP;
  placed.push({ name, file, sx, sy, w, h, dx, dy });
}
const width = Math.max(...placed.map((p) => p.dx + p.w));
const height = Math.max(...placed.map((p) => p.dy + p.h));
const rgba = Buffer.alloc(width * height * 4);
for (const p of placed) {
  const src = load(p.file);
  for (let y = 0; y < p.h; y++) {
    for (let i = 0; i < p.w; i++) {
      const from = ((p.sy + y) * src.width + p.sx + i) * 4;
      const to = ((p.dy + y) * width + p.dx + i) * 4;
      src.data.copy(rgba, to, from, from + 4);
    }
  }
}

// Palette: transparent plus the 15 most common colours, merging colours
// that are nearly the same. Barely visible edge pixels become transparent.
const key = (i) => rgba.readUInt32BE(i);
const counts = new Map();
for (let i = 0; i < rgba.length; i += 4) {
  if (rgba[i + 3] >= 32) counts.set(key(i), (counts.get(key(i)) ?? 0) + 1);
}
const channels = (c) => [c >>> 24, (c >>> 16) & 255, (c >>> 8) & 255, c & 255];
const distance = (a, b) =>
  channels(a).reduce((sum, v, i) => sum + (v - channels(b)[i]) ** 2, 0);
const palette = [0];
for (const [color] of [...counts].sort((a, b) => b[1] - a[1])) {
  if (palette.length === 16) break;
  if (palette.slice(1).every((p) => distance(p, color) > 30 ** 2)) {
    palette.push(color);
  }
}
const indices = new Uint8Array(width * height);
for (let i = 0; i < indices.length; i++) {
  if (rgba[i * 4 + 3] < 32) continue;
  let best = 1;
  for (let p = 2; p < palette.length; p++) {
    if (distance(palette[p], key(i * 4)) < distance(palette[best], key(i * 4))) {
      best = p;
    }
  }
  indices[i] = best;
}

// A 4-bit indexed PNG with per-entry alpha (tRNS).
const crcTable = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
const crc = (buf) => {
  let c = 0xffffffff;
  for (const b of buf) c = crcTable[(c ^ b) & 255] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
};
const chunk = (type, data) => {
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const out = Buffer.alloc(body.length + 8);
  out.writeUInt32BE(data.length, 0);
  body.copy(out, 4);
  out.writeUInt32BE(crc(body), body.length + 4);
  return out;
};
const ihdr = Buffer.alloc(13);
ihdr.writeUInt32BE(width, 0);
ihdr.writeUInt32BE(height, 4);
ihdr.set([4, 3, 0, 0, 0], 8);
const rowBytes = Math.ceil(width / 2);
const raw = Buffer.alloc((rowBytes + 1) * height);
for (let y = 0; y < height; y++) {
  for (let i = 0; i < width; i++) {
    const at = y * (rowBytes + 1) + 1 + (i >> 1);
    raw[at] |= indices[y * width + i] << (i % 2 ? 0 : 4);
  }
}
const png = Buffer.concat([
  Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
  chunk('IHDR', ihdr),
  chunk('PLTE', Buffer.from(palette.flatMap((c) => channels(c).slice(0, 3)))),
  chunk('tRNS', Buffer.from(palette.map((c) => c & 255))),
  chunk('IDAT', deflateSync(raw, { level: 9 })),
  chunk('IEND', Buffer.alloc(0)),
]);

const frames = placed
  .map((p) => `  ${p.name}: { x: ${p.dx}, y: ${p.dy}, width: ${p.w}, height: ${p.h} },`)
  .join('\n');
writeFileSync(
  join(root, 'src', 'sprites.ts'),
  `// Generated by scripts/generate-sprites.mjs from assets/. Do not edit.

export const SHEET = {
  uri: 'data:image/png;base64,${png.toString('base64')}',
  width: ${width},
  height: ${height},
};

export const FRAMES = {
${frames}
};

export type FrameName = keyof typeof FRAMES;
`
);
if (process.env.SHEET_PREVIEW) writeFileSync(process.env.SHEET_PREVIEW, png);
console.log(
  `sheet ${width}x${height}, ${palette.length} colours, ${png.length} bytes`
);
